const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps/web_app/web/app.js', 'utf8');
const literalLine = source.split('\n').find(value => value.startsWith('function literalOverlapLabel('));
const literalLabel = vm.runInNewContext(`(${literalLine})`);
assert.equal(literalLabel(0), 'No complete statement matches');
assert.equal(literalLabel(0.5), '50% text overlap');
assert.equal(literalLabel(null), 'Text overlap unavailable');
assert.equal(literalLabel(NaN), 'Text overlap unavailable');
assert.equal((source.match(/literalOverlapLabel\(row\.score\)/g) || []).length, 2);
const rangeLine = source.split('\n').find(value => value.startsWith('function repeatabilityRangeMessage('));
const rangeMessage = vm.runInNewContext(`(${rangeLine})`);
assert.match(rangeMessage({previous_lower:75,previous_upper:75,lower_change:-25,upper_change:25}), /Previous range 75–75%; lower bound change -25, upper bound change \+25/);
assert.equal(rangeMessage(null), 'Previous range unavailable. ');
assert.equal(rangeMessage({previous_lower:75,previous_upper:75,lower_change:50,upper_change:0}), 'Previous range unavailable. ');
assert.ok(source.includes('repeatabilityRangeMessage(r.range_change)'), 'repeatability display must include range changes');
const dimensionLine = source.split('\n').find(value => value.startsWith('function repeatabilityDimensionMessage('));
assert.ok(dimensionLine);
const dimensions = vm.runInNewContext(`(${dimensionLine})`);
assert.match(dimensions({changed_weights:1,changed_statuses:2,changed_evidence:1}), /1 weight change, 2 judgment changes and 1 evidence change.*overlap/);
assert.equal(dimensions({changed_judgments:1}), '');
assert.ok(source.includes('repeatabilityDimensionMessage(r)'));
const line = source.split('\n').find(value => value.startsWith('function fitBadgeLabel('));
assert.ok(line, 'fit badge formatter must exist');
const label = vm.runInNewContext(`(${line})`);
assert.equal(label(55, {lower: 10, upper: 100},'included','supported',false,'complete'), '55% AI estimate · 10–100% range');
assert.equal(label(75, {lower: 75, upper: 75},'included','supported',false,'complete'), '75% AI estimate · 75–75% range');
assert.equal(label(50, {lower: 0, upper: 100},'included','supported',false,'complete'), 'Insufficient evidence · 0–100% range');
assert.match(label(50, {lower: 0, upper: 100}, null, null, false, 'none_used'), /no qualifications used/);
assert.equal(label(55, null,'included','supported',false,'complete'), 'AI estimate unavailable · range unavailable');
assert.equal(label(55, {lower: 60, upper: 100},'included','supported',false,'complete'), 'AI estimate unavailable · range unavailable');
assert.equal(label(-1, {lower: 0, upper: 100}), 'Estimate unavailable');
assert.match(label(75,{lower:50,upper:100},'needs_review'), /check preferences/);
assert.match(label(75,{lower:50,upper:100},'possible_conflict'), /possible preference conflict/);
assert.doesNotMatch(label(75,{lower:50,upper:100},'included'), /check preferences|conflict/);
assert.match(label(80,{lower:60,upper:100},'included','needs_review'), /required criterion unknown/);
assert.match(label(80,{lower:60,upper:100},'included','possible_conflict'), /AI flagged possible required conflict/);
assert.match(label(80,{lower:60,upper:100},'included','none_identified'), /no required criteria identified/);
assert.match(label(80,{lower:60,upper:100},'included','incomplete'), /requirement check incomplete/);
assert.match(label(80,{lower:60,upper:100},'included','unavailable'), /required criteria unavailable/);
assert.match(label(80,{lower:60,upper:100},'included','possible_conflict',true), /possible required conflict.*requirement check incomplete/);
assert.match(label(80,{lower:60,upper:100},'included','needs_review',true), /required criterion unknown.*requirement check incomplete/);
assert.equal((label(80,{lower:60,upper:100},'included','incomplete',true).match(/requirement check incomplete/g) || []).length,1);
assert.match(label(80,{lower:60,upper:100},'included','supported',false,'limited'), /qualification input limited/);
assert.match(label(80,{lower:60,upper:100},'included','supported',false,'selected'), /selected qualifications/);
assert.match(label(80,{lower:60,upper:100},'included','supported',false,'unavailable'), /qualification coverage unavailable/);
assert.match(label(80,{lower:60,upper:100}), /preference coverage unavailable.*required criteria unavailable.*requirement audit unavailable.*qualification coverage unavailable/);
assert.match(label(80,{lower:60,upper:100},'unexpected','invented',null,'unexpected'), /preference coverage unavailable.*required criteria unavailable.*requirement audit unavailable.*qualification coverage unavailable/);
assert.match(label(80,{lower:60,upper:100},'constructor','toString',null,'constructor'), /preference coverage unavailable.*required criteria unavailable.*requirement audit unavailable.*qualification coverage unavailable/);
assert.match(label(80,{lower:60,upper:100},'included','supported',false,'none'), /no reviewed qualifications/);
assert.ok(source.includes('fitBadgeWithReview(fitBadgeLabel(item.score,item.score_range,item.preference_coverage,item.requirement_coverage,item.requirement_audit_incomplete,item.qualification_coverage)'), 'batch badges must use their stored range and coverage');
assert.ok(source.includes('fitBadgeWithReview(fitBadgeLabel(score,result.assessment?.score_range,result.assessment?.preference_coverage,result.assessment?.requirement_coverage,result.assessment?.requirement_audit_incomplete,result.assessment?.qualification_coverage)'), 'new assessments must use their range and coverage');
const headlineLine = source.split('\n').find(value => value.startsWith('function fitAssessmentHeadline('));
const headline = vm.runInNewContext(`(${headlineLine})`);
assert.match(headline({score:55, summary:'fixture'}), /unavailable/);
assert.match(headline({score:55, score_range:{lower:60,upper:100}, summary:'fixture'}), /unavailable/);
assert.match(headline({score:50, score_range:{lower:0,upper:100}, summary:'fixture'}), /Insufficient evidence/);
assert.match(headline({score:75, score_range:{lower:50,upper:100}, summary:'fixture'}), /75%/);
const reviewedLine = source.split('\n').find(value => value.startsWith('function fitBadgeWithReview('));
const reviewed = vm.runInNewContext(`(${reviewedLine})`);
assert.equal(reviewed('50% AI',75,{lower:50,upper:100}),'50% AI · Reviewed 75% (50–100%)');
assert.equal(reviewed('50% AI',50,{lower:0,upper:100}),'50% AI · Reviewed: insufficient evidence');
assert.equal(reviewed('50% AI',null,null),'50% AI');
assert.equal(reviewed('50% AI',101,{lower:0,upper:100}),'50% AI · Review unavailable');
const scoreLine = source.split('\n').find(value => value.startsWith('function fitRubricScore('));
assert.ok(scoreLine, 'temporary correction calculation must exist');
const calculate = vm.runInNewContext(`(${scoreLine})`);
const rubric = [
  {importance:'required',status:'supported'},
  {importance:'required',status:'unknown'},
  {importance:'preferred',status:'contradicted'}
];
assert.equal(JSON.stringify(calculate(rubric)), JSON.stringify({score:64,lower:43,upper:86}));
rubric[0].status='unknown';
assert.equal(JSON.stringify(calculate(rubric)), JSON.stringify({score:43,lower:0,upper:86}));
assert.equal(calculate([{importance:'required',status:'invented'}]), null);
assert.ok(source.includes('beside the unchanged AI estimate on the job badge'), 'temporary edits must be clearly labelled');
assert.ok(source.includes('fitReviewControls(a.rubric,'), 'assessment must expose the controls');
const controlsLine = source.split('\n').find(value => value.startsWith('function fitReviewControls('));
function fakeNode(tag,text='') { return {tag,textContent:text,children:[],listeners:{},append(...nodes){this.children.push(...nodes);},setAttribute(){},addEventListener(event,callback){this.listeners[event]=callback;}}; }
const context = {fitRubricScore:calculate,element:(tag,text)=>fakeNode(tag,text),document:{createElement:tag=>fakeNode(tag)}};
const controls = vm.runInNewContext(`(${controlsLine})`,context)(rubric);
const selects = controls.children.filter(node=>node.tag==='label' && node.textContent!=='Importance').map(node=>node.children[0]);
assert.equal(selects.length,3);
assert.equal(controls.children.at(-1).textContent,'Review scenario: 43% · 0–86% range');
selects[1].value='supported';
selects[1].listeners.change();
assert.equal(controls.children.at(-1).textContent,'Review scenario: 64% · 43–86% range');
selects[0].value='exclude';
selects[0].listeners.change();
assert.equal(controls.children.at(-1).textContent,'Review scenario: 75% · 75–75% range');
selects[1].value='exclude';
selects[2].value='exclude';
selects[2].listeners.change();
assert.equal(controls.children.at(-1).textContent,'Review scenario unavailable (select 1–12 criteria).');
console.log('Fit badge UI checks passed.');
