const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps/web_app/web/app.js', 'utf8');
const line = source.split('\n').find(value => value.startsWith('function showDocumentEvidence('));
assert.ok(line);
const show = vm.runInNewContext(`(${line})`, {element: (tag,text) => ({tag,text})});
const panel = {children:[], append(...nodes){this.children.push(...nodes);}};
show(panel, {evidence_check:{status:'partial',items:[{id:1,status:'supported',explanation:'Fixture'}],unchecked:[{id:2,reason:'unavailable'}]}});
assert.ok(panel.children.some(item => item.text.includes('2 (unavailable)')));
assert.ok(panel.children.some(item => item.text.includes('Paragraph 1: supported')));
const framingPanel = {children:[], append(...nodes){this.children.push(...nodes);}};
show(framingPanel, {framing_check:{status:'needs_review',explanation:'Unverified claim'},evidence_check:{status:'completed',items:[]}});
assert.ok(framingPanel.children.some(item => item.text.includes('Opening and closing check: needs_review') && item.text.includes('Unverified claim')));
const unavailable = {children:[], append(...nodes){this.children.push(...nodes);}};
show(unavailable, {framing_check:{status:'unavailable'}});
assert.ok(unavailable.children.some(item => item.text.includes('Opening and closing check was unavailable')));
console.log('Document evidence UI checks passed.');
