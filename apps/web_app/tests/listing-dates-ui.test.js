const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source=fs.readFileSync('apps/web_app/web/app.js','utf8');
const line=source.split('\n').find(s=>s.startsWith('function showListingDateEvidence('));
assert.ok(line);
const element=(tag,text,cls)=>({tag,textContent:text,className:cls});
const helperStart=source.indexOf('function listingDeadlinePast('),helperEnd=source.indexOf('\nfunction showListingDateEvidence(',helperStart);
const context={element,Date,Number};
vm.createContext(context);
const deadline=vm.runInContext(`${source.slice(helperStart,helperEnd)}; listingDeadlinePast`,context);
const inspected=vm.runInContext('inspectedListingDeadlineNotice',context);
const show=vm.runInContext(`(${line})`,context);
const panel={items:[],append(item){this.items.push(item);}};
show(panel,{salary_evidence:null,posting_date_evidence:'2026-10-01',valid_through_evidence:'2026-11-30T23:59:00+01:00',matches_current_url:false,captured_at:1750000000});
assert.match(panel.items[0].textContent,/different URL/);
assert.match(panel.items[1].textContent,/posting date: 2026-10-01/);
assert.match(panel.items[2].textContent,/2026-11-30T23:59:00\+01:00/);
assert.match(panel.items[3].textContent,/not proof that the role is open or closed/);
const empty={items:[],append(item){this.items.push(item);}};show(empty,{});assert.equal(empty.items.length,0);
const now=Date.parse('2026-11-03T00:00:00Z');
assert.equal(deadline('2026-11-01',now),false);
assert.equal(deadline('2026-11-01',now+1),true);
assert.equal(deadline('2026-11-03T00:30:00+01:00',now),true);
assert.equal(deadline('2026-11-03T00:30:00-01:00',now),false);
for(const invalid of ['2026-02-30','2026-11-01T00:00:00','yesterday','2026-11-01T00:00:00+99:00'])assert.equal(deadline(invalid,now),false);
const expired={items:[],append(item){this.items.push(item);}};show(expired,{valid_through_evidence:'2020-01-01',matches_current_url:true});assert.ok(expired.items.some(item=>item.textContent.includes('deadline may have passed')));
const stale={items:[],append(item){this.items.push(item);}};show(stale,{valid_through_evidence:'2020-01-01',matches_current_url:false});assert.ok(!stale.items.some(item=>item.textContent.includes('deadline may have passed')));
const expiredJob={saved:{existing:false},job:{extraction:'structured',valid_through_evidence:'2020-01-01'}};
assert.match(inspected(expiredJob),/deadline that may have passed/);
assert.equal(inspected({...expiredJob,saved:{existing:true}}),'');
assert.equal(inspected({...expiredJob,job:{...expiredJob.job,extraction:'local_model'}}),'');
console.log('Listing date evidence UI checks passed.');
