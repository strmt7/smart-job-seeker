// Exercise the actual UI comparison helper without starting the app or a browser.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const source = fs.readFileSync(path.join(__dirname, '../web/app.js'), 'utf8');
const start = source.indexOf('function visualComparisonStatus(');
const end = source.indexOf('function showAutomaticFit(', start);
assert.ok(start >= 0 && end > start, 'UI comparison helper must be present');
const status = vm.runInNewContext(`${source.slice(start, end)}; visualComparisonStatus`);
const needsRefresh = vm.runInNewContext(`${source.slice(start, end)}; visualReviewNeedsQueueRefresh`);
assert.equal(needsRefresh({comparisons:[{status:'differs_from_transcription'}]}), true);
assert.equal(needsRefresh({comparisons:[{status:'unobserved',dom_status:'unconfirmed'}]}), true);
assert.equal(needsRefresh({comparisons:[{status:'unobserved'}]}), false);
assert.equal(needsRefresh({comparisons:[]}), false);
const field = {label: 'Email', expected: 'candidate@example.invalid', dom_status:'matches'};
const observed = {label: 'email', visible_value: field.expected};
assert.equal(status(field, [field], [observed], true), 'transcription and live value match reviewed answer');
assert.equal(status({...field,dom_status:'unconfirmed'}, [field], [observed], true), 'live field value not confirmed');
assert.equal(status({...field,dom_status:undefined}, [field], [observed], true), 'live field value not confirmed');
const ambiguous = {...field, ambiguous: true};
assert.equal(status(ambiguous, [ambiguous], [observed], true), 'not uniquely observed');
assert.equal(status(ambiguous, [ambiguous], [observed], false), 'capture changed or freshness could not be confirmed');
assert.equal(status(field, [field], [observed], false), 'capture changed or freshness could not be confirmed');
assert.equal(status(field, [field], [], true), 'not uniquely observed');
assert.equal(status(field, [field], [observed, observed], true), 'not uniquely observed');
assert.equal(status(field, [field, field], [observed], true), 'not uniquely observed');
assert.equal(status(field, [field], [{label: 'Email', visible_value: 'other'}], true), 'transcription differs from reviewed answer');
const multiline = {label: 'First name', expected: 'Example', dom_status:'matches'};
assert.equal(status(multiline, [multiline], [{label: ' FIRST\n  NAME ', visible_value: 'Example'}], true), 'transcription and live value match reviewed answer');
assert.equal(status(multiline, [multiline, {label: 'FIRST\nNAME', expected: 'Example'}], [{label: 'First name', visible_value: 'Example'}], true), 'not uniquely observed');
assert.equal(status(multiline, [multiline], [{label: 'FIRST NAME', visible_value: 'Example'}, {label: 'First\nname', visible_value: 'Example'}], true), 'not uniquely observed');
assert.equal(status(multiline, [multiline], [{label: '\ufeffFirst name', visible_value: 'Example'}], true), 'not uniquely observed');
const international = {label: 'Prénom complet', expected: 'Élodie', dom_status:'matches'};
const translated = {label: 'PRÉNOM\u00a0COMPLET', visible_value: 'Élodie'};
assert.equal(status(international, [international], [translated], true), 'transcription and live value match reviewed answer');
assert.equal(status(international, [international, {label: 'PRÉNOM\u00a0COMPLET', expected: 'Élodie'}], [translated], true), 'not uniquely observed');
assert.equal(status(international, [international], [translated, {label: 'Prénom complet', visible_value: 'Élodie'}], true), 'not uniquely observed');
console.log('Visual comparison UI checks passed.');
