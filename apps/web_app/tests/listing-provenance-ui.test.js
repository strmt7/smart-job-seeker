const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps/web_app/web/app.js', 'utf8');
const start = source.indexOf('function showListingProvenance(');
const end = source.indexOf('\nfunction ', start);
assert.ok(start >= 0 && end > start);
function element(tag, text = '') { return {tag, text}; }
let recoveredRoles;
const context = {element,showOtherRoles:(_panel,result)=>{recoveredRoles=result.job;}};
vm.runInNewContext(source.slice(start, end), context);
const panel = {items:[], append(...items){this.items.push(...items)}};
context.showListingProvenance(panel,{matches_current_url:true,extraction_provenance:{kind:'local_model',matches_current_listing:true,partial_structured_fields:['requisition_id'],page_text_truncated:true,warnings:['Review source']}});
let text=panel.items.map(item=>item.text).join('\n');
assert.match(text,/Local model/);
assert.match(text,/requisition number/);
assert.match(text,/truncated/);
assert.doesNotMatch(text,/may not match the current listing/);
context.showListingProvenance(panel,{matches_current_url:true,extraction_provenance:{kind:'local_model',matches_current_listing:true,other_roles_status:'review',other_role_assessments:[{title:'Fictional Analyst',status:'historical',evidence:'Past roles'}]}});
assert.deepEqual(Array.from(recoveredRoles.other_open_roles),['Fictional Analyst']);
assert.equal(recoveredRoles.other_role_assessments[0].status,'historical');
panel.items=[];
context.showListingProvenance(panel,{matches_current_url:false,extraction_provenance:{kind:'structured',matches_current_listing:false}});
text=panel.items.map(item=>item.text).join('\n');
assert.match(text,/may not match the current listing/);
panel.items=[];
context.showListingProvenance(panel,{matches_current_url:true,extraction_provenance:{kind:'local_model',matches_current_listing:true,employer_audit:{status:'conflict',evidence:'University Example is hiring.'}}});
text=panel.items.map(item=>item.text).join('\n');
assert.match(text,/possible employer conflict.*can be wrong/);
assert.match(text,/Model-cited page text: University Example is hiring/);
panel.items=[];
context.showListingProvenance(panel,{matches_current_url:true,extraction_provenance:{kind:'local_model',matches_current_listing:true,deadline_excerpt:'Applications close: 30 November 2026'}});
text=panel.items.map(item=>item.text).join('\n');
assert.match(text,/Possible application deadline selected by local AI: Applications close: 30 November 2026.*Verify/);
console.log('Listing provenance UI checks passed.');
