const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('apps/web_app/web/app.js','utf8');
const line=prefix=>{const value=source.split('\n').find(item=>item.startsWith(prefix));assert.ok(value);return value;};
const values=new Map();
const storage={getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
const context={};
vm.runInNewContext([line('function loadJobSelection('),line('function saveJobSelection('),line('function reconcileJobSelection(')].join('\n'),context);
const selection=context.loadJobSelection(storage);
selection.add('job-a');selection.add('job-b');selection.add('job-c');
assert.equal(context.saveJobSelection(storage,selection),true);
const restored=context.loadJobSelection(storage);
assert.deepEqual([...restored],['job-a','job-b','job-c']);
context.reconcileJobSelection(restored,[{job:{id:'job-a',state:'discovered'}},{job:{id:'job-b',state:'shortlisted'}}]);
assert.deepEqual([...restored],['job-a']);
context.saveJobSelection(storage,restored);
assert.deepEqual([...context.loadJobSelection(storage)],['job-a']);
values.set('waypoint-selected-jobs','{"bad":true}');
assert.equal(context.loadJobSelection(storage).size,0);
values.set('waypoint-selected-jobs','["a",null]');
assert.equal(context.loadJobSelection(storage).size,0);
assert.equal(context.saveJobSelection({setItem(){throw Error('quota');}},selection),false);
assert.match(line('function updateSelection()'),/!selectionReconciled/);
assert.match(line("document.querySelector('#shortlist-selected').addEventListener"),/!selectionReconciled/);
console.log('Job selection restoration and reconciliation checks passed.');
