const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps/web_app/web/app.js', 'utf8');
const draft = source.match(/function useFormDraft\([^\n]+/)[0];
const counter = source.match(/function attachFormLengthCounter\([^\n]+/)[0];
const make = vm.runInNewContext(`(function(element){${draft}\n${counter}\nreturn {useFormDraft,attachFormLengthCounter};})`);
const element = () => ({textContent:'', className:'',setAttribute(){}});
const {useFormDraft,attachFormLengthCounter} = make(element);
const input = {value:'',listeners:{},addEventListener(event,fn){this.listeners[event]=fn;},focus(){}};
const parent = {children:[],append(node){this.children.push(node);}};
attachFormLengthCounter(parent,input,{max_length_utf16:3,field_type:'text'});
useFormDraft(input,{text:'A😀'},'draft-id',true);
assert.match(parent.children[0].textContent,/3 of 3/);
assert.equal(input._draftId,'draft-id');
input.value='AB😀'; input.listeners.input();
assert.match(parent.children[0].textContent,/4 of 3.*exceeds/);
assert.equal(parent.children[0].className,'review-label');
const none={children:[],append(node){this.children.push(node);}};
attachFormLengthCounter(none,input,{max_length_utf16:null,field_type:'text'});
assert.equal(none.children.length,0);
console.log('Form length counter checks passed.');
