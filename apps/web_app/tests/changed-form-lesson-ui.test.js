const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps/web_app/web/app.js', 'utf8');
const line = source.split('\n').find(item => item.startsWith('function prepareChangedFormLesson('));
assert.ok(line);
const fields = Object.fromEntries(['stage','platform','observation','response','outcome','control','note'].map(name => [name, {value: 'previous'}]));
fields.confirmed = {checked: true};
fields.use_note_in_model = {checked: true};
const ctx = {experienceForm: {elements: fields}, experienceStatus: {}, experiencePanel: {open: false, scrollIntoView() {}}, location: {}, clearRelatedExperiences() {}, syncWorkspaceNavigation() {}};
vm.runInNewContext(`(${line})`, ctx)();
assert.equal(fields.observation.value, 'form_changed');
assert.equal(fields.stage.value, 'enter_information');
assert.equal(fields.platform.value, '');
assert.equal(fields.response.value, 'inspect_manually');
assert.equal(fields.outcome.value, 'unknown');
assert.equal(fields.confirmed.checked, false);
assert.equal(fields.use_note_in_model.checked, false);
assert.equal(fields.control.value, 'previous');
assert.equal(fields.note.value, 'previous');
assert.match(ctx.experienceStatus.textContent, /No lesson has been saved/);
assert.ok(ctx.experiencePanel.open);
assert.ok(source.includes("error.message.includes('The form changed after filling; inspect the new fields and review it again')"));
console.log('Changed-form lesson UI checks passed.');
