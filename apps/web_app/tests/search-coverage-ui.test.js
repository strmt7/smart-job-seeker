const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps/web_app/web/app.js', 'utf8');
const start = source.indexOf('function searchCoverage(');
const end = source.indexOf('\nfunction webCandidate(', start);
assert.ok(start >= 0 && end > start, 'search coverage renderer must exist');
const render = vm.runInNewContext(`(${source.slice(start, end)})`);
assert.match(render({results_examined: 30, results_reported: 100, unresponsive_engines: null, limited: true}), /30 examined of 100 provider results.*Provider did not report engine availability/);
assert.match(render({results_examined: 0, results_reported: 0, unresponsive_engines: 0}), /0 engines reported unavailable/);
assert.match(render({results_examined: 2, unresponsive_engines: 1}), /1 engine reported unavailable/);
assert.match(render({results_examined:100,results_reported:100,limited:true,batch_limit_omitted:2,unresponsive_engines:0}), /2 omitted by the batch limit/);
const batchStart = source.indexOf('function webBatchSummary(');
const batchEnd = source.indexOf('\nasync function followWebBatch(', batchStart);
assert.ok(batchStart >= 0 && batchEnd > batchStart, 'batch coverage summary must exist');
const batchSummary = vm.runInNewContext(`(${source.slice(batchStart, batchEnd)})`);
const mixed = batchSummary({status:'complete',processed:3,total:5,coverage:{succeeded_pages:2,failed_pages:1,unattempted_pages:2,limited_pages:1,pages_with_unresponsive_engines:1,pages_with_unknown_engine_availability:1}});
assert.match(mixed, /3 of 5 pages attempted.*2 succeeded, 1 failed, 2 not attempted/);
assert.match(mixed, /1 page had limited results.*1 page reported unavailable engines.*1 page did not report engine availability/);
assert.match(batchSummary({status:'complete',processed:0,total:2,cancelled:true,coverage:{succeeded_pages:0,failed_pages:0,unattempted_pages:2}}), /stopped.*0 succeeded, 0 failed, 2 not attempted/);
const repeatedLine = source.split('\n').find(line=>line.startsWith('function repeatedCandidateDetails('));
assert.ok(repeatedLine);
const make = (tag,text='')=>({tag,text,children:[],append(...items){this.children.push(...items);}});
const repeated = vm.runInNewContext(`(${repeatedLine})`,{element:make});
const references = Array.from({length:12},(_,index)=>({title:`Role ${index}`,url:`https://example.org/${index}`,engines:['fictional engine']}));
const details = repeated({previously_seen:15,repeated_references:references});
assert.equal(details.children[0].text,'Repeated results: showing 10 of 15');
assert.match(details.children[2].text,/Role 0.*https:\/\/example.org\/0.*fictional engine/);
assert.equal(details.children.length,12);
assert.equal(repeated({previously_seen:1}),null);
console.log('Search coverage UI checks passed.');
