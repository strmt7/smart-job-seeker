const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps/web_app/web/app.js', 'utf8');
const helper = source.split('\n').find(line => line.startsWith('function visualReviewStopControl('));
assert.ok(helper);
let pending = null, response = { requested: true }, calls = [];
const context = { element(tag, text) { return { tag, textContent: text, disabled: false, addEventListener(_, fn) { this.click = fn; } }; }, pendingDocumentVisual: () => pending, api: async (...args) => { calls.push(args); if (response instanceof Error) throw response; return response; } };
vm.createContext(context);
vm.runInContext(helper, context);
(async () => {
  let control = context.visualReviewStopControl({ id: 'doc' });
  assert.equal(control.stop.disabled, true);
  pending = { task: 'task', doc: 'doc', job: 'job' };
  control = context.visualReviewStopControl({ id: 'doc' });
  assert.equal(control.stop.disabled, false);
  await control.stop.click();
  assert.equal(calls[0][0], '/api/documents/visual-review-cancel');
  assert.equal(calls[0][1].task_id, 'task');
  assert.equal(control.stop.disabled, true);
  assert.match(control.notice.textContent, /current render or model call/);
  response = new Error('offline');
  control = context.visualReviewStopControl({ id: 'doc' });
  await control.stop.click();
  assert.equal(control.stop.disabled, false);
  assert.match(control.notice.textContent, /offline/);
  response = { requested: false };
  await control.stop.click();
  assert.match(control.notice.textContent, /already finished/);
  assert.ok(source.includes('panel.append(select,button,stopper.stop,stopper.notice,preview,edit,output)'));
})().catch(e => { console.error(e); process.exitCode = 1; });
