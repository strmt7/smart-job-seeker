const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('apps/web_app/web/app.js','utf8');
const line=source.split('\n').find(x=>x.startsWith('function appendSavedExportRecheck('));
assert.ok(line);
assert.ok(source.includes('appendSavedExportRecheck(entry,job,record);'));
const noticeLine=source.split('\n').find(x=>x.startsWith('function emptyAttemptNotice('));
assert.ok(noticeLine);
const notice=vm.runInNewContext(`(${noticeLine})`);
assert.match(notice({truncated:false,unreadable:0}),/No saved preparation attempts/);
assert.match(notice({truncated:true,unreadable:0}),/Some records may be missing/);
assert.match(notice({truncated:false,unreadable:1}),/Some records may be missing/);
const controls=source.slice(source.indexOf('if(historyPage>0 || data.has_more){'),source.indexOf('if(data.scan_truncated || data.email_handoffs_truncated)'));
assert.ok(controls.startsWith('if(historyPage>0'));
const nodes=[];let navigated=0;
const element=(tag,text)=>({tag,text,children:[],append(...values){this.children.push(...values)},addEventListener(_,fn){this.click=fn}});
const context={historyPage:0,data:{has_more:true},attemptsList:{append(...values){nodes.push(...values)}},element,loadHistory:()=>{navigated++}};
vm.runInNewContext(controls,context);
assert.equal(nodes[0].children[0].disabled,true);
nodes[0].children[2].click();
assert.equal(context.historyPage,1);
assert.equal(navigated,1);
nodes.length=0;
context.data.has_more=false;
vm.runInNewContext(controls,context);
assert.equal(nodes[0].children[2].disabled,true);
nodes[0].children[0].click();
assert.equal(context.historyPage,0);
assert.equal(navigated,2);
(async()=>{
  const calls=[];
  const context={element:(tag,text)=>({tag,text,addEventListener:(_,fn)=>{context.click=fn;}}),recheckExportText:async(result,output)=>{calls.push([result,output]);}};
  const run=vm.runInNewContext(`(${line})`,context);
  const entry={children:[],append(...nodes){this.children.push(...nodes)}};
  run(entry,{id:'job'},{});
  assert.equal(entry.children.length,0);
  run(entry,{id:'job'},{export_document_id:'doc',attempt_id:'attempt'});
  assert.equal(entry.children.length,2);
  await context.click();
  assert.equal(calls[0][0].job_id,'job');
  assert.equal(calls[0][0].id,'doc');
  assert.equal(calls[0][0].attempt_id,'attempt');
  assert.equal(calls[0][1],entry.children[1]);
  assert.equal(entry.children[0].disabled,false);
  console.log('Saved export recheck history UI checks passed.');
})().catch(error=>{console.error(error);process.exitCode=1});
