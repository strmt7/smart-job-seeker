const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('apps/web_app/web/app.js', 'utf8');
const line = source.split('\n').find(value => value.startsWith('function formFieldManualNotice('));
assert.ok(line);
const notice = vm.runInNewContext(`(${line})`);
const phone = {selector:'#phone', label:'Phone', sensitive:true, required:true};
assert.match(notice(phone, {model_review_selectors:['#phone']}), /This field needs additional review/);
assert.match(notice(phone, {model_review_selectors:['#phone'],visible:false}), /browser is hidden; close this review and inspect again with a visible browser/);
assert.doesNotMatch(notice(phone, {model_review_selectors:['#phone'],visible:true}), /browser is hidden/);
assert.doesNotMatch(notice(phone, {model_review_selectors:['#phone']}), /browser is hidden/);
assert.match(notice(phone, {}), /manual handling in the browser/);
assert.match(notice({...phone,sensitive:false}, {visible:false}), /Page changes may not be retained/);
assert.doesNotMatch(notice({...phone,sensitive:false,required:false}, {visible:false}), /browser is hidden/);
assert.match(notice({...phone, sensitive:false}, {}), /Needs an answer/);
assert.match(notice({...phone, sensitive:false, required:false}, {}), /Not mapped/);
assert.ok(source.includes("formFieldManualNotice(field,result)"));
const reasonsLine = source.split('\n').find(value => value.startsWith('function visibleFormReviewReasons('));
const reasons = vm.runInNewContext(`(${reasonsLine})`);
const input = {fields:[phone],model_review_selectors:['#phone'],manual_review:['Model flagged a field for manual review: Phone','Other review reason']};
assert.equal(JSON.stringify(reasons(input)),JSON.stringify(['Other review reason']));
assert.equal(reasons({...input,model_review_selectors:[]}).length,2);
assert.equal(reasons({...input,fields:[]}).length,2);
const groupedLine=source.split('\n').find(value=>value.startsWith('function appendFormReviewReasons('));
const node=(tag,text='')=>({tag,text,children:[],append(...items){this.children.push(...items);}});
const grouping=vm.runInNewContext(`(${groupedLine})`,{element:(tag,text)=>node(tag,text),document:{createElement:tag=>node(tag)}});
const panel=node('div');
const custom=['One','Two','Three','Four'].map(label=>`a required custom control needs manual review: ${label}`);
grouping(panel,[custom[0],'captcha present',...custom.slice(1),'other warning']);
assert.equal(panel.children[0].tag,'details');
assert.match(panel.children[0].children[0].text,/4 custom-control warnings/);
assert.deepEqual(panel.children[0].children.slice(1).map(item=>item.text),custom);
assert.equal(panel.children[1].text,'captcha present');
assert.equal(panel.children[2].text,'other warning');
const short=node('div');grouping(short,custom.slice(0,3));assert.equal(short.children.length,3);assert.ok(short.children.every(item=>item.tag==='p'));
assert.ok(source.includes('appendFormReviewReasons(panel,visibleFormReviewReasons(result))'));
console.log('Manual field reason checks passed.');
